const PAPER = "#EEECE3";
const STROKE = 16.6;

/**
 * La pila completa, en las coordenadas de la invitación. `viewBox` deja elegir
 * qué parte mostrar: la invitación entera, o solo la pila (la vista previa de
 * WhatsApp).
 */
export function InvitationPile({
  viewBox = "0 0 1080 1920",
  style,
  width,
  height,
}: {
  viewBox?: string;
  style?: CSSProperties;
  width?: number | string;
  height?: number | string;
}) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={viewBox}
      width={width}
      height={height}
      style={style}
      aria-hidden="true"
      preserveAspectRatio="xMidYMax slice"
    >
      {INVITATION_ROKIS.map((roki, index) => (
        // Las posiciones son fijas y el orden es el de las capas: el índice es
        // una clave estable.
        // biome-ignore lint/suspicious/noArrayIndexKey: lista fija
        <g key={index} transform={roki.matrix}>
          <path
            d={`${roki.outline.d}${roki.outline.close}`}
            transform={`translate(${roki.outline.x} ${roki.outline.y})`}
            fill={PAPER}
          />
          <g
            fill="none"
            stroke={roki.color}
            strokeWidth={STROKE}
            strokeLinecap="round"
            strokeLinejoin="round"
          >
            <path
              d={roki.outline.d}
              transform={`translate(${roki.outline.x} ${roki.outline.y})`}
            />
            <path
              d={roki.neck.d}
              transform={`translate(${roki.neck.x} ${roki.neck.y})`}
            />
            <path
              d={roki.eye.d}
              transform={`translate(${roki.eye.x} ${roki.eye.y})`}
            />
          </g>
        </g>
      ))}
    </svg>
  );
}
